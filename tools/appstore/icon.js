// Usage: NODE_PATH=$(npm root -g) node tools/appstore/icon.js   -> the app icon (concept 1 of icon.html) at 1024×1024
// icon.html holds all six concepts from the October 2026 icon round (?i=1..6); the app uses 1. The hero balloon is
// the in-game one: balloon3dCore, rig3d and flame3d are copied from the prototype into game3d.js on every run.
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const proto = fs.readFileSync(path.join(__dirname, '../../prototype/balloon-baron.html'), 'utf8').split('\n');
const fn = name => {
  const a = proto.findIndex(l => l.startsWith(`function ${name}(`));
  const b = proto.findIndex((l, i) => i > a && l === '}');
  if (a < 0 || b < 0) throw new Error('missing ' + name);
  return proto.slice(a, b + 1).join('\n');
};
fs.writeFileSync(path.join(__dirname, 'game3d.js'), '/* Generated by icon.js from prototype/balloon-baron.html; do not edit. */\nlet T = 0.62; /* the flame\'s flicker frame */\n'
  + ['balloon3dCore', 'rig3d', 'flame3d'].map(fn).join('\n') + '\n');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1024, height: 1024 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto('file://' + path.join(__dirname, 'icon.html') + '?i=' + (process.argv[2] || 1));
  await p.waitForFunction(() => document.title === 'done', null, { timeout: 60000 });
  const out = process.argv[3] || path.join(__dirname, '../../BalloonBaron/Assets.xcassets/AppIcon.appiconset/AppIcon.png');
  await p.locator('#c').screenshot({ path: out });
  console.log(out, errs);
  await b.close();
})();
